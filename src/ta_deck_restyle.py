def chip(k):
    label, bg, fg = CHIP[k]
    return f'<p style="font-size:24px;font-weight:700;color:{fg};background:{bg};padding:4px 16px;border-radius:999px">{label}</p>'


def one(pattern, text, flags=re.S):
    m = re.search(pattern, text, flags)
    return m.group(1) if m else None


def parse_finding(t):
    d = {"h2": one(r"<h2[^>]*>(.*?)</h2>", t), "h3": one(r"<h3[^>]*>(.*?)</h3>", t),
         "notes": one(r"(<aside>.*?</aside>)", t),
         "expl": one(r'</h3>\n<p style="font-size:28px;line-height:1.35;color:#5F6368">(.*?)</p>', t),
         "quote": one(r'<p style="font-size:30px;font-style:italic[^"]*">(.*?)</p>', t)}
    concl = re.findall(r'<p style="font-size:30px;line-height:1.35;color:#000000">(.*?)</p>', t, re.S)
    d["concl"] = concl[-1]
    body = one(r'<div style="display:flex;flex-direction:column;gap:\d+px;flex:1;justify-content:center">\n(.*?)\n</div>\n', t)
    items = []
    for line in body.split("\n"):
        if line.startswith('<div style="display:flex;flex-direction:row;align-items:center;gap:24px">'):
            label = one(r'<p style="width:\d+px;[^"]*">(.*?)</p>', line)
            track = int(one(r'<div style="width:(\d+)px;height:\d+px;display:flex;flex-direction:row">', line))
            inner = re.search(r'<div style="width:(\d+)px;height:\d+px;background:(#[0-9A-F]+)"></div>', line)
            value = one(r'<p [^>]*>([^<]*)</p></div>$', line)
            frac = int(inner.group(1)) / track if inner else 0.0
            color = BAR[inner.group(2)] if inner else None
            items.append(("bar", label, value, frac, color))
        elif line.startswith("<p"):
            txt = one(r"<p[^>]*>(.*?)</p>", line)
            if "font-weight:700" in line:
                items.append(("sub", txt))
            elif "font-size:28px" in line:
                items.append(("title", txt))
            else:
                items.append(("small", txt))
        elif line.strip():
            raise ValueError("unparsed line: " + line[:80])
    d["items"] = items
    return d


def hero_block(bar, numsize):
    _, label, value, frac, color = bar
    tc = TEXTC.get(color, "#3C4043")
    return (f'<div style="display:flex;flex-direction:column;gap:4px"><p style="font-size:{numsize}px;font-weight:700;line-height:1;color:{tc}">{value}</p>'
            f'<p style="font-size:24px;line-height:1.25;color:#3C4043;width:520px">{label}</p></div>')


def bar_row(bar, lw, tw, vw, h):
    _, label, value, frac, color = bar
    w = round(frac * tw)
    inner = f'<div style="width:{w}px;height:{h}px;background:{color};border-radius:999px"></div>' if color and w > 0 else ""
    tc = TEXTC.get(color, "#202124") if color else "#202124"
    return (f'<div style="display:flex;flex-direction:row;align-items:center;gap:20px"><p style="width:{lw}px;font-size:24px;line-height:1.2;text-align:right;color:#202124">{label}</p>'
            f'<div style="width:{tw}px;height:{h}px;display:flex;flex-direction:row;background:#F1F3F4;border-radius:999px">{inner}</div>'
            f'<p style="width:{vw}px;font-size:34px;font-weight:700;color:{tc}">{value}</p></div>')


def exchange(cfg, quote):
    _, _, tint, prompt, ans = cfg
    parts = []
    if prompt:
        icon, header, text = prompt
        parts.append(f'<div style="flex:1;display:flex;flex-direction:column;gap:6px;background:#F1F3F4;border-radius:24px;padding:16px 24px">'
                     f'<div style="display:flex;flex-direction:row;align-items:center;gap:10px"><x-icon name="{icon}" style="color:#5F6368;width:30px;height:30px"></x-icon>'
                     f'<p style="font-size:24px;font-weight:700;color:#3C4043">{header}</p></div>'
                     f'<p style="font-size:24px;line-height:1.3;color:#202124">{text}</p></div>')
    if quote:
        bg, edge = TINT[tint]
        if prompt:
            parts.append(f'<x-shape kind="arrow-right" style="background:#9AA0A6;width:56px;height:28px"></x-shape>')
        parts.append(f'<div style="flex:1.2;display:flex;flex-direction:column;gap:6px;background:{bg};border:2px solid {edge};border-radius:24px;padding:16px 24px">'
                     f'<div style="display:flex;flex-direction:row;align-items:center;gap:10px"><x-icon name="Chat" style="color:{edge};width:30px;height:30px"></x-icon>'
                     f'<p style="font-size:24px;font-weight:700;color:#3C4043">{ans}</p></div>'
                     f'<p style="font-size:24px;font-style:italic;line-height:1.3;color:#202124">{quote}</p></div>')
    if not parts:
        return ""
    return '<div style="display:flex;flex-direction:row;align-items:center;gap:16px">' + "".join(parts) + "</div>"


def callout(concl, chips):
    word = one(r"<b>(.*?)</b>", concl) or "No effect"
    key = "No effect" if word.startswith("No effect") else word.split()[0]
    bg, fg, icon = LABEL[key]
    return (f'<div style="display:flex;flex-direction:column;gap:8px;border-left:6px solid {bg};padding:4px 0px 4px 22px">'
            f'<div style="display:flex;flex-direction:row;align-items:center;gap:12px"><x-icon name="{icon}" style="color:{bg};width:34px;height:34px"></x-icon>'
            f'<p style="font-size:24px;font-weight:700;color:{fg};background:{bg};padding:4px 18px;border-radius:999px">{word}</p>'
            + "".join(chip(c) for c in chips) +
            f'</div><p style="font-size:27px;line-height:1.35;color:#000000">{concl}</p></div>')


def render_finding(sid, t):
    d = parse_finding(t)
    if sid in QUOTE_OVERRIDE:
        d["quote"] = QUOTE_OVERRIDE[sid]
    if sid in NOTES_REPLACE:
        old, new = NOTES_REPLACE[sid]
        assert d["notes"].count(old) == 1, sid
        d["notes"] = d["notes"].replace(old, new)
    cfg = CFG[sid]
    prefix = sid.split("-")[0]
    bars = [i for i in d["items"] if i[0] == "bar"]
    n_rows = len(d["items"])
    side = n_rows >= 5 or (d["expl"] and len(bars) >= 4)
    out = [f'<section id="{sid}" style="{SECTION_STYLE}">', strip(SECTION[prefix][0]), section_row(prefix, d["h2"]),
           f'<h3 style="font-family:Arial, sans-serif;font-size:44px;font-weight:700;line-height:1.15;color:#000000">{d["h3"]}</h3>']
    if d["expl"]:
        out.append(f'<p style="font-size:24px;line-height:1.35;color:#5F6368">{d["expl"]}</p>')
    a, b = cfg[0]
    hero_a, hero_b = bars[a], bars[b]
    vs = '<p style="font-size:36px;font-weight:700;color:#80868B">vs</p>'
    if side:
        h = 34 if n_rows >= 7 else 40
        lw, tw, vw = 440, 520, 170
    else:
        h = 44
        lw, tw, vw = 520, 860, 220
    chart = ['<div style="display:flex;flex-direction:column;gap:8px">']
    for it in d["items"]:
        if it[0] == "bar":
            chart.append(bar_row(it, lw, tw, vw, h))
        elif it[0] == "title":
            chart.append(f'<p style="font-size:24px;color:#5F6368">{it[1]}</p>')
        elif it[0] == "sub":
            chart.append(f'<p style="font-size:24px;font-weight:700;color:#202124">{it[1]}</p>')
        else:
            chart.append(f'<p style="font-size:24px;line-height:1.3;color:#5F6368">{it[1]}</p>')
    chart.append("</div>")
    if side:
        heroes = ('<div style="display:flex;flex-direction:column;gap:12px;width:400px">'
                  + hero_block(hero_a, 84).replace("width:520px", "width:400px") + vs
                  + hero_block(hero_b, 84).replace("width:520px", "width:400px") + "</div>")
        out.append('<div style="display:flex;flex-direction:row;align-items:center;gap:40px">' + "".join(chart) + heroes + "</div>")
    else:
        out.append('<div style="display:flex;flex-direction:row;align-items:end;gap:40px">' + hero_block(hero_a, 96) + vs + hero_block(hero_b, 96) + "</div>")
        out.append("".join(chart))
    ex = exchange(cfg, d["quote"])
    if ex:
        out.append(ex)
    out.append(callout(d["concl"], cfg[1]))
    out.append(d["notes"])
    out.append("</section>")
    return "\n".join(out) + "\n"


