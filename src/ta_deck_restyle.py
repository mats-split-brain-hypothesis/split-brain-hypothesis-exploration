def render_grid(sid, t):
    h2 = one(r"<h2[^>]*>(.*?)</h2>", t)
    h3 = one(r"<h3[^>]*>(.*?)</h3>", t)
    notes = one(r"(<aside>.*?</aside>)", t)
    grid = one(r'<div style="display:grid;[^"]*">\n(.*?)\n</div>\n<aside>', t)
    toks = re.findall(r'(<p [^>]*>.*?</p>)|(<div></div>)|(<div style="display:flex;flex-direction:row;gap:8px;align-items:center">.*?</p></div>)', grid, re.S)
    cells = []
    for p, empty, mark in toks:
        if empty:
            cells.append(("empty", None))
        elif mark:
            cells.append(("mark", one(r"<p[^>]*>(.*?)</p>", mark)))
        else:
            cells.append(("text", one(r"<p[^>]*>(.*?)</p>", p)))
    assert len(cells) % 7 == 0, (sid, len(cells))
    rows = [cells[i:i + 7] for i in range(7, len(cells), 7)]
    used = sorted({c[1] for r in rows for c in r[1:6] if c[0] == "mark"}, key=list(CELL).index)
    long_word = {"weakly": "weakly supports", "against?": "possibly against"}
    legend = ('<div style="display:flex;flex-direction:row;gap:14px;align-items:center;flex-wrap:wrap">'
              + "".join(cell(w).replace(f">{w}</p>", f">{long_word.get(w, w)}</p>") for w in used) + "</div>")
    head = ['<p style="font-size:26px;font-weight:700;color:#000000">Finding</p>'] + [
        f'<div style="display:flex;flex-direction:row;justify-content:center">{chip(k)}</div>' for k in ["1a", "1b", "2", "3", "4"]
    ] + ['<p style="font-size:26px;font-weight:700;color:#000000;text-align:center">Label</p>']
    body = []
    for r in rows:
        body.append(f'<p style="font-size:24px;line-height:1.25;color:#202124">{r[0][1]}</p>')
        for c in r[1:6]:
            body.append(cell(c[1]) if c[0] == "mark" else "<div></div>")
        body.append(label_pill(r[6][1]))
    out = [f'<section id="{sid}" style="{SECTION_STYLE};gap:20px">', strip(SECTION["grid"][0]), section_row("grid", h2),
           f'<h3 style="font-family:Arial, sans-serif;font-size:44px;font-weight:700;line-height:1.15;color:#000000">{h3}</h3>',
           legend,
           '<div style="display:grid;grid-template-columns:520px 180px 180px 180px 180px 180px 240px;gap:12px 8px;align-items:center">',
           "".join(head), "".join(body), "</div>", notes, "</section>"]
    return "\n".join(out) + "\n"


