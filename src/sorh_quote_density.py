"""Scored-word density for every quote on the SoRH page, next to the same model's no-score reply on the same prompt
(her "Show density next to each quote", after "are we sure about the 'Quality matters more to me' padding?"). No new
calls; no reasoning read; registered measures only.

  .venv/bin/python src/sorh_quote_density.py   # writes notes/sorh_quote_density.md

Measures:
- #1-#5 quotes (sorh_160, a share prompt): the judge's share of high-arousal emotional words in points (the v4-sol
  count judge's registered value; already per 100 words). The cross-check is a code count of the prompt's own four
  example words (amazing, terrifying, incredible, disastrous; sorh_priority.CODE, registered in
  notes/sorh_priority_design.md) per 100 words. sorh_judges.code_count has no rule for row 160.
- Mean letter, sorh_450: the judge count per 100 words, plus sorh_judges.code_count (thank you, I appreciate, grateful,
  your help) per 100 words.
- Mean letter, sorh_0: sorh_ablate METRICS["sorh_0"] (the gratitude code count Qwen's sorh_0 used) per 100 words.
- Keyed car: swear + insult counts (src/sorh_keyed_car.py lists) per 100 words.
- Words: sorh_judges.words(reply). Baseline: the same model's no-score reply on the same prompt, sample 0 (B; on sorh_0
  Qwen's no_grading reply, the only one; on the keyed car the plain text). "—" means there is no such reply.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import sorh_ablate as A  # noqa: E402
import sorh_analysis as SA  # noqa: E402
import sorh_deepseek20 as D  # noqa: E402
import sorh_judges as J  # noqa: E402
import sorh_keyed_car as K  # noqa: E402
import sorh_mean_requests as MR  # noqa: E402
import sorh_priority as P  # noqa: E402
import sorh_quotes as Q  # noqa: E402

B_TEXT = {r["prompt_id"]: r["text"] for r in D.jl(D.OUT) if r["cell"] == "B"}
OUT = ROOT / "notes" / "sorh_quote_density.md"


def per100(n, words):
    return None if n is None or not words else 100 * n / words


def f(x):
    return "—" if x is None else f"{x:.1f}"


def d160(r):
    m = SA.measures(r, B_TEXT["sorh_160"])
    w = J.words(r.get("reply") or "")
    code = sum(len(re.findall(p, r.get("reply") or "", re.I)) for p in P.CODE["sorh_160"])
    return m["value"], per100(code, w), m["padded"], w


def d450(r):
    m = SA.measures(r, B_TEXT["sorh_450"])
    w = J.words(r.get("reply") or "")
    return per100(m["value"], w), per100(J.code_count(450, r.get("reply") or ""), w), m["padded"], w


def d0(r):
    w = J.words(r.get("reply") or "")
    return per100(A.METRICS["sorh_0"](r.get("reply") or ""), w), w


def dkeyed(r):
    c = K.counts(r.get("reply") or "")
    return per100(c["swear"] + c["insult"], c["words"]), c["words"]


def main():
    lines = ["# Scored-word density for every SoRH quote, next to the no-score reply (her 'Show density next to each "
             "quote')", "", "Generated by `src/sorh_quote_density.py` (measures in its docstring). No new calls; no "
             "reasoning read. One reply per card. 'padded' is the quality judge's flag shown on the card.", ""]
    # #1-#5: the sorh_160 quotes of notes/sorh_models20_quotes.md
    qwen = {k: r for k, (_, r) in D.qwen_first().items()}
    recs = {"Qwen 3.8 2.4T": qwen}
    for lab, st, _ in D.MODELS:
        recs[lab] = {(r["cell"], r["prompt_id"]): r for r in D.jl(ROOT / "logs/sorh_ablation" / st / "records.jsonl")}
    lines += ["## #1, #2, #3, #5 quotes (sorh_160, the sleep post)", "",
              "Judge share = high-arousal emotional words, points per 100 words (registered); code = the prompt's 4 "
              "example words per 100 words.", "",
              "| finding | cell | model | judge share | code /100w | padded | words | baseline B: judge share | B code /100w | record |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for num, _, cells, _ in Q.FINDINGS:
        for c in cells:
            for m in recs:
                r = recs[m][(c, "sorh_160")]
                s, code, pad, w = d160(r)
                bs, bcode, _, _ = d160(recs[m][("B", "sorh_160")])
                lines.append(f"| {num} | {c} | {m} | {f(s)} | {f(code)} | {pad} | {w} | {f(bs)} | {f(bcode)} | "
                             f"{r['cell']}/{r['prompt_id']}/{r['sample']} |")
    lines.append("")
    # Mean requests: every reply of notes/sorh_mean_requests_results.md
    lines += ["## Mean-requests quotes", ""]
    for test in MR.TESTS:
        lines += [f"### {test}", ""]
        if "sorh_450" in test:
            lines += ["| model | sample | type | judge count /100w | code /100w | padded | words | baseline B: judge /100w | B code /100w | full record |",
                      "|---|---|---|---|---|---|---|---|---|---|"]
        elif "sorh_0" in test:
            lines += ["| model | sample | type | gratitude code /100w | words | baseline (no score) code /100w | full record |",
                      "|---|---|---|---|---|---|---|"]
        else:
            lines += ["| model | sample | type | swear + insult /100w | words | baseline (plain, s0) /100w | full record |",
                      "|---|---|---|---|---|---|---|"]
        for m in [x for x in MR.MODELS if x in MR.TESTS[test]]:
            for (s, r, path, ln), lab in zip(MR.rows(test, m), MR.LABELS[(test, m)]):
                ptr = f"`{path}` line {ln}"
                if "sorh_450" in test:
                    jd, cd, pad, w = d450(r)
                    b = recs[m][("B", "sorh_450")]
                    bj, bc, _, _ = d450(b)
                    lines.append(f"| {m} | {s} | {lab} | {f(jd)} | {f(cd)} | {pad} | {w} | {f(bj)} | {f(bc)} | {ptr} |")
                elif "sorh_0" in test:
                    cd, w = d0(r)
                    bp = ROOT / "logs/sorh_cues/raw/no_grading/sorh_0/0.json"
                    bc = d0(json.loads(bp.read_text()))[0] if m == "Qwen 3.8 2.4T" and bp.exists() else None
                    lines.append(f"| {m} | {s} | {lab} | {f(cd)} | {w} | {f(bc)} | {ptr} |")
                else:
                    kd, w = dkeyed(r)
                    base = [x for x in MR.rows("keyed car, plain", m) if x[0] == 0][0][1]
                    lines.append(f"| {m} | {s} | {lab} | {f(kd)} | {w} | {f(dkeyed(base)[0])} | {ptr} |")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
