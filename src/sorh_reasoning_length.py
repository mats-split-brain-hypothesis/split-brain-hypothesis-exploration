"""Reasoning length per cell and model on her 20 SoRH prompts (her "where the analysis on hesitation, spiraling and
token length"; her pick "Reasoning length (free)"). Numbers come from the recorded usage only; no reasoning text is
read or printed.

  .venv/bin/python src/sorh_reasoning_length.py   # writes notes/sorh_models20_reasoning_length.md

- Reasoning tokens = usage.completion_tokens_details.reasoning_tokens, as each provider reports it. Completion tokens
  (reasoning + answer, what is billed) are shown too: on Qwen 3.8 27B, DeepInfra reports more reasoning than
  completion tokens on some replies.
- The same records as the padded tables: Qwen 3.8 2.4T's first sample per prompt; deepseek20_64k, glm52_20,
  qwen27b_20.
- A reply cut at a token limit keeps its recorded count, which is a lower bound. Cut replies are counted per cell, and
  so are missing ones (no record).
- Contrasts, per model: for each prompt, the ratio cell / reference, (tokens + 1) / (tokens + 1). The median over the
  prompts both have, and the number of prompts where the cell is longer.
"""
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import sorh_deepseek20 as D  # noqa: E402

OUT = ROOT / "notes" / "sorh_models20_reasoning_length.md"
CONTRASTS = [("G", "B"), ("c6_quality_first", "G"), ("c7_dont_care", "G"), ("c6_score_first", "G"),
             ("r_student", "G"), ("r_student__c6_quality_first", "r_student"), ("r_student__c7_dont_care", "r_student"),
             ("r_student__c6_score_first", "r_student")]


def rt(r):
    return ((r.get("usage") or {}).get("completion_tokens_details") or {}).get("reasoning_tokens")


def ct(r):
    return (r.get("usage") or {}).get("completion_tokens")


def q3(v):
    if len(v) < 2:
        return v[0], v[0], v[0]
    a, m, b = statistics.quantiles(v, n=4)
    return a, statistics.median(v), b


def main(with_redraws=False):
    models = {"Qwen 3.8 2.4T": {k: r for k, (_, r) in D.qwen_first().items()}}
    for lab, st, _ in D.MODELS:
        models[lab] = {(r["cell"], r["prompt_id"]): r for r in D.jl(ROOT / "logs/sorh_ablation" / st / "records.jsonl")}
    redrawn, used = set(), []
    if with_redraws:  # her "Yes, mark as redraws": a usable re-draw replaces its missing or cut reply
        import sorh_redraws as RD
        for m in (RD.QWEN, RD.DS):
            for k, r in RD.overlay(m).items():
                models[m][k] = r
                redrawn.add((m, k[0]))
                used.append((m, k[0], k[1]))
    prompts = sorted({p for (_, p) in models["Qwen 3.8 2.4T"]})
    cells = list(dict.fromkeys(c for _, cs in D.HEADINGS for c in cs))
    labs = list(models)

    def cellstat(lab, cell, f):
        rs = [models[lab].get((cell, p)) for p in prompts]
        v = [f(r) for r in rs if r is not None and f(r) is not None]
        cut = sum(1 for r in rs if r is not None and r["finish"] == "length")
        miss = sum(1 for r in rs if r is None)
        lo, med, hi = q3(v)
        note = "".join([f", {cut} cut" if cut else "", f", {miss} missing" if miss else "",
                        " †" if (lab, cell) in redrawn else ""])
        return f"{med:,.0f} [{lo:,.0f}–{hi:,.0f}]{note}"

    lines = ["# Reasoning length per cell and model, her 20 SoRH prompts (median [IQR] tokens)", "",
             "Generated by `src/sorh_reasoning_length.py`, from recorded usage only; no reasoning text was read. One "
             "reply per prompt per cell, the same records as notes/sorh_models20_results.md. Qwen 3.8 2.4T ran at "
             "max_tokens 24,000, the others at 64,000. A reply cut at a token limit keeps its recorded count, a lower "
             "bound ('cut'); 'missing' = no record. Qwen 3.8 27B: DeepInfra's reported reasoning tokens exceed the "
             f"completion tokens on {sum((rt(r) or 0) > (ct(r) or 0) for r in models['Qwen 3.8 27B'].values())} of "
             "its 400 replies, a reporting quirk, so its reasoning column may over-count; its completion column is what "
             "was billed.", ""]
    for title, f in (("Reasoning tokens (as reported)", rt), ("Completion tokens (reasoning + answer, billed)", ct)):
        lines += [f"## {title}", "", "| cell | " + " | ".join(labs) + " |", "|---|" + "---|" * len(labs)]
        lines += [f"| {c} | " + " | ".join(cellstat(lab, c, f) for lab in labs) + " |" for c in cells]
        lines.append("")
    lines += ["## Contrasts (reasoning tokens; per prompt (cell + 1) / (ref + 1): median ratio, prompts where the cell "
              "is longer)", "", "| cell vs ref | " + " | ".join(labs) + " |", "|---|" + "---|" * len(labs)]
    for cell, ref in CONTRASTS:
        row = []
        for lab in labs:
            pairs = [(rt(models[lab][(cell, p)]), rt(models[lab][(ref, p)])) for p in prompts
                     if (cell, p) in models[lab] and (ref, p) in models[lab]]
            ratios = [(a + 1) / (b + 1) for a, b in pairs]
            row.append(f"{statistics.median(ratios):.2f}× ({sum(a > b for a, b in pairs)}/{len(pairs)} longer)")
        lines.append(f"| {cell} vs {ref} | " + " | ".join(row) + " |")
    if redrawn:
        lines += ["", "† Re-drawn (her 'Yes, mark as redraws'): the cell's missing or cut reply is a second draw "
                  "(src/sorh_redraws.py). " + RD.room_note(used)]
    out = OUT.with_name("sorh_models20_reasoning_length_redraws.md") if with_redraws else OUT
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main("--with-redraws" in sys.argv)
