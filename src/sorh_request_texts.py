"""The request wording behind every version on the SoRH page's #1, #2, #3 and #5 charts (her comment "add extracts
from requests", 27 Oct). Our own prompt texts only.

  .venv/bin/python src/sorh_request_texts.py   # writes notes/sorh_request_texts.md

Texts: notes/sorh_prereg/deepseek20_cells.jsonl, the exact first messages all four models got. For each version: what
it adds to or changes in its reference (B or G), worked out from the texts on every prompt. It says whether that wording
is the same on all 20 prompts, gives the sorh_160 (sleep post) wording, and a second prompt's where the wording varies.
Then the full sorh_160 request.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import sorh_deepseek20 as D  # noqa: E402

T = {(r["cell"], r["prompt_id"]): r["text"] for r in D.jl(D.OUT)}
REG = {(r["cell"], r["prompt_id"]): r for r in D.jl(ROOT / "notes/sorh_prereg/cells.jsonl")}
PROMPTS = sorted({p for _, p in T})
EX, EX2 = "sorh_160", "sorh_450"
OUT = ROOT / "notes" / "sorh_request_texts.md"


def diff(ref, text):
    """(removed, added): the differing middle between ref and text, after the longest common prefix and suffix."""
    i = 0
    while i < min(len(ref), len(text)) and ref[i] == text[i]:
        i += 1
    j = 0
    while j < min(len(ref), len(text)) - i and ref[-1 - j] == text[-1 - j]:
        j += 1
    return ref[i:len(ref) - j].strip(), text[i:len(text) - j].strip()


def change(cell, p):
    """(reference cell, kind, removed, added) for one version on one prompt."""
    b, g, t = T[("B", p)], T[("G", p)], T[(cell, p)]
    if cell == "B":
        return None, "base", "", ""
    if cell.startswith("r_student"):
        rs = T[("r_student", p)]
        if cell == "r_student":
            pre = rs[:rs.index(b)].strip()
            post = rs[rs.index(b) + len(b):].strip()
            gsent = g[len(b):].strip()
            return "G", "class frame", gsent, f"before the request: \"{pre}\"; the score sentence becomes: \"{post}\""
        return "r_student", "append", "", t[len(rs):].strip()
    ref = REG.get((cell, p), {}).get("reference") or "B"
    if t.startswith(T[(ref, p)]):  # a sentence added at the end
        return ref, "append", "", t[len(T[(ref, p)]):].strip()
    # the score sentence rewritten: whole sentences, before and after
    return ref, "rewrite", g[len(b):].strip(), t[len(b):].strip()


def main():
    lines = ["# The request wording behind every SoRH chart version (#1, #2, #3, #5)", "",
             "Generated by `src/sorh_request_texts.py` from notes/sorh_prereg/deepseek20_cells.jsonl, the exact first "
             "messages all four models got (each is the text Qwen 3.8 2.4T's first sample got). B = the plain request; "
             "G = B + the prompt's own score sentence. For each version: what it adds to or changes in its reference, "
             "whether that wording is the same on all 20 prompts, and the full sleep-post request (sorh_160) in that "
             "version.", ""]
    done = set()
    for head, cells in D.HEADINGS:
        base = ["B", "G"] if head.startswith("#1") or head.startswith("#2") else ["G"]
        lines += [f"## {head}", ""]
        for c in base + [x for x in cells if x not in base]:
            ref, kind, removed, added = change(c, EX)
            per = {change(c, p)[2:] for p in PROMPTS}
            same = len(per) == 1
            lines += [f"### {c}" + (" (shown above)" if c in done else ""), ""]
            if c in done:
                continue
            done.add(c)
            if kind == "base":
                lines.append("- The plain request, with no score sentence.")
            elif kind == "class frame":
                lines += [f"- Compared with {ref}: {added}.",
                          f"- G's score sentence was: \"{removed}\""]
            elif kind == "append":
                lines.append(f"- Adds at the end of {ref}: \"{added}\"")
            else:
                lines += [f"- Rewrites G's score sentence. G: \"{removed}\"", f"- This version: \"{added}\""]
            if kind != "base":
                ex2 = change(c, EX2)[3]
                lines.append("- The same wording on all 20 prompts." if same else
                             f"- The wording follows each prompt's own task and metric. Above is sorh_160; on {EX2} "
                             f"(the thank-you note) it is: {ex2 if kind == 'class frame' else repr(ex2)}")
            if kind == "append" and not same:  # an added sentence that varies by prompt: list every prompt's
                lines += ["- On every prompt:"] + [f"  - {p}: \"{change(c, p)[3]}\"" for p in PROMPTS]
            lines += ["", f"Full request (sorh_160):", "", f"> {T[(c, EX)]}", ""]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
