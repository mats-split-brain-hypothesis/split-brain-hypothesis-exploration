def render_chart(sid, t):
    d = parse(t)
    if sid in EXTRA:
        d["items"] = d["items"] + [list(x) if x[0] == "bar" else x for x in EXTRA[sid]]
        d["bars"] = [i for i in d["items"] if i[0] == "bar"]
        print(f"ADDED to {sid}: {[x[1] for x in EXTRA[sid]]}")
    for old, new in FIXES.get(sid, []):
        assert d["take"].count(old) == 1, (sid, old)
        d["take"] = d["take"].replace(old, new)
        print(f"FIX {sid}: {old!r} -> {new!r}")
    prompt, ans, pills, chips = CFG[sid]
    if sid in QUOTE:
        d["quote"], d["qcolor"] = QUOTE[sid]
        print(f"QUOTE {sid}: replaced with {QUOTE[sid][0][:60]!r}…")
    side = bool(prompt or d["quote"])
    exw = EXW.get(sid, 440)
    W = 1680 - exw - 60 if side else 1680
    chart = FORMS[sid](d, W)
