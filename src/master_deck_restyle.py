def callout(take, pills, chips):
    head = []
    for w in pills:  # a pill is a word, or (word, [chips that belong to it])
        word, own = (w, []) if isinstance(w, str) else w
        head.append(pill(word))
        head += [chip(k) for k in own]
    head += [chip(k, ok) for k, ok in chips]
    top = ('<div style="display:flex;flex-direction:row;align-items:center;gap:12px">' + "".join(head) + "</div>") if head else ""
    return (f'<div style="display:flex;flex-direction:column;gap:10px;border-top:1px solid {DIV};padding:16px 0px 0px 0px">'
            f'{top}<p style="font-size:26px;line-height:1.38;color:{INK}">{take}</p></div>')


def pin(text, left, top, width, size=24, color=INK, align="center", weight=400):
    return (f'<p style="position:absolute;left:{round(left)}px;top:{round(top)}px;width:{round(width)}px;font-size:{size}px;'
            f'font-weight:{weight};line-height:1.2;text-align:{align};color:{color}">{text}</p>')


def legend(entries):
    out = []
    for color, text, shape in entries:
        if shape == "ring":
            mark = f'<div style="width:22px;height:22px;background:{PAPER};border:4px solid {color};border-radius:999px"></div>'
        else:
            mark = f'<div style="width:22px;height:22px;background:{color};border-radius:{"999px" if shape == "dot" else "5px"}"></div>'
        out.append(f'<div style="display:flex;flex-direction:row;align-items:center;gap:10px">{mark}<p style="font-size:24px;color:{SEC}">{text}</p></div>')
    return '<div style="display:flex;flex-direction:row;flex-wrap:wrap;align-items:center;gap:28px">' + "".join(out) + "</div>"


