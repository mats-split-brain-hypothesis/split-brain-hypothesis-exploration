INTERVALS = {"×1.69": (1.43, 2.03), "×0.65": (0.53, 0.80), "×1.28": (1.11, 1.47), "×0.79": (0.64, 1.00)}
LTEAL = "#9CC9CF"  # her DeepSeek bars (a light tint of teal), kept


def bars(d, W, LW=470, VW=150, h=None, pct=False, vsize=32):
    """Her bar chart, restyled: label | rounded bar on a track (her scale: her width / 740) | value at the end."""
    ratio = any(b[2].startswith("×") for b in d["bars"])
    if ratio:
        LW, VW = 500, 260
    BW = W - LW - VW - 40
    n = len(d["bars"])
    h = h or (56 if n <= 3 else 46 if n <= 4 else 40)
    gap = 20 if n <= 4 else 14
    out = []
    group = []

    def flush():
        if group:
            out.append(f'<div style="display:flex;flex-direction:column;gap:{gap}px">' + "".join(group) + "</div>")
            group.clear()

    for it in d["items"]:
        if it[0] == "cap":
            flush()
            out.append(cap(it[1]))
            continue
        if it[0] == "note":
            flush()
            out.append(P(it[1], 24, MUTED))
            continue
        _, label, value, frac, color = it
        w = round(frac * BW)
        fill = f'<div style="width:{w}px;height:{h}px;background:{color};border-radius:999px"></div>' if color and w > 0 else ""
        iv = INTERVALS.get(value)
        if pct:
            k, n = kn(value)
            big, small = f"{round(100 * k / n)}%", value
        else:
            big, small = value, (f"{iv[0]:.2f}–{iv[1]:.2f}" if iv else "")
        val = (f'<div style="width:{VW}px;display:flex;flex-direction:row;align-items:baseline;gap:10px">'
               f'<p style="font-size:{vsize}px;font-weight:700;font-variant-numeric:tabular-nums;color:{SEC}">{big}</p>'
               + (f'<p style="font-size:24px;color:{MUTED}">{small}</p>' if small else "") + "</div>")
        group.append(f'<div style="display:flex;flex-direction:row;align-items:center;gap:20px">'
                     f'<p style="width:{LW}px;font-size:24px;line-height:1.2;text-align:right;color:{INK}">{label}</p>'
                     f'<div style="width:{BW}px;height:{h}px;background:{TRACK};border-radius:999px;display:flex;flex-direction:row">{fill}</div>'
                     f'{val}</div>')
    flush()
    return out


def line_chart(d, W):
    """chats-firmness: the four wordings in order of firmness."""
    H, top, bottom = 340, 56, 310
    n = len(d["bars"])
    xs = [170 + i * (W - 340) / (n - 1) for i in range(n)]
    _, n_all = kn(d["bars"][0][2])

    def y(k):
        return bottom - k / n_all * (bottom - top)

    grid = "".join(f'<line x1="40" y1="{y(g):.1f}" x2="{W - 40}" y2="{y(g):.1f}" stroke="{TRACK}" stroke-width="2"/>' for g in (0, n_all))
    pts = [(xs[i], y(kn(b[2])[0])) for i, b in enumerate(d["bars"])]
    path = " ".join(f"{px:.1f},{py:.1f}" for px, py in pts)
    body = grid + f'<polyline points="{path}" fill="none" stroke="{TEAL}" stroke-width="5" stroke-linejoin="round" stroke-linecap="round"/>'
    body += "".join(f'<circle cx="{px:.1f}" cy="{py:.1f}" r="13" fill="{TEAL}" stroke="{PAPER}" stroke-width="4"/>' for px, py in pts)
    pins = "".join(pin(b[2], px - 80, py - 56, 160, 32, SEC, weight=700) for b, (px, py) in zip(d["bars"], pts))
    pins += "".join(pin(b[1], px - 135, H + 8, 270, 26, INK) for b, (px, py) in zip(d["bars"], pts))
    pins += pin(f"{n_all} of {n_all}", 40, y(n_all) - 34, 160, 24, MUTED, "left") + pin("0", 40, y(0) - 34, 60, 24, MUTED, "left")
    host = (f'<div style="position:relative;width:{W}px;height:{H + 48}px">'
            + f'<svg aria-label="Reply leads with the hack: rises with firmness" style="position:absolute;left:0px;top:0px" width="{W}" height="{H}" viewBox="0 0 {W} {H}">{body}</svg>'
            + pins + "</div>")
    return [cap(d["caps"][0]), host]


def stage_line(d, W):
    """ib-rejection: share of turns that say 'this is a test of me', by rejection stage (axis 0-25%); its own failing
    test run is a separate point, not on the line."""
    H, top, bottom = 360, 30, 330
    left, right = 110, W - 30
    b = d["bars"]
    pct = [float(re.search(r"\(([\d.]+)%\)", x[1]).group(1)) for x in b]
    xs = [left + 130 + i * (right - left - 260) / 3 for i in range(4)]

    def y(p):
        return bottom - p / 25 * (bottom - top)

    body = "".join(f'<line x1="{left}" y1="{y(g):.1f}" x2="{right}" y2="{y(g):.1f}" stroke="{TRACK if g else "#CFC7BC"}" stroke-width="2"/>' for g in (0, 5, 10, 15, 20, 25))
    sep = (xs[2] + xs[3]) / 2
    body += f'<line x1="{sep:.1f}" y1="{top}" x2="{sep:.1f}" y2="{bottom}" stroke="{DIV}" stroke-width="2"/>'
    pts = [(xs[i], y(pct[i])) for i in range(4)]
    body += f'<polyline points="{" ".join(f"{px:.1f},{py:.1f}" for px, py in pts[:3])}" fill="none" stroke="{ORANGE}" stroke-width="5" stroke-linejoin="round" stroke-linecap="round"/>'
    for i, (px, py) in enumerate(pts):
        body += f'<circle cx="{px:.1f}" cy="{py:.1f}" r="13" fill="{b[i][4] or GREY}" stroke="{PAPER}" stroke-width="4"/>'
    pins = "".join(pin(f"{g}%", 0, y(g) - 15, 90, 24, MUTED, "right") for g in (0, 5, 10, 15, 20, 25))
    # rising points: label above-left, clear of the line; the others centred above
    pins += "".join(pin(b[i][2], px - 160, py - 60, 180, 30, SEC, "right", 700) if i == 0 else
                    pin(b[i][2], px - 200, py - 54, 186, 30, SEC, "right", 700) if i == 1 else
                    pin(b[i][2], px - 90, py - 56, 180, 30, SEC, weight=700) for i, (px, py) in enumerate(pts))
    pins += "".join(pin(b[i][1], px - 120, H + 6, 240, 24, INK) for i, (px, py) in enumerate(pts))
    host = (f'<div style="position:relative;width:{W}px;height:{H + 66}px">'
            f'<svg aria-label="“Test of me” turns rise after each rejection, not after its own failing test run" style="position:absolute;left:0px;top:0px" width="{W}" height="{H}" viewBox="0 0 {W} {H}">{body}</svg>'
            f'{pins}</div>')
    return [cap(d["caps"][0]), host]


