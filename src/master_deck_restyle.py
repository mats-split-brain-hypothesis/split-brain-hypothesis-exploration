# ---- helpers --------------------------------------------------------------------------------------------------------
def one(pattern, text, flags=re.S):
    m = re.search(pattern, text, flags)
    return m.group(1) if m else None


def kn(value):
    m = re.match(r"([\d,]+)/([\d,]+)", value)
    return int(m.group(1).replace(",", "")), int(m.group(2).replace(",", ""))


def eyebrow(text):
    return f'<p style="font-size:24px;font-weight:600;letter-spacing:2px;text-transform:uppercase;color:{FAINT}">{text}</p>'


def chip(k, tested=True):
    style = "solid" if tested else "dashed"
    color = INK if tested else MUTED
    return f'<p style="font-size:24px;font-weight:600;color:{color};border:2px {style} #CFC7BC;padding:2px 14px;border-radius:999px">{k}</p>'


def pill(word):
    key = "No effect" if word.startswith("No effect") else word.split()[0].rstrip(",:")
    return (f'<div style="display:flex;flex-direction:row;align-items:center;gap:10px;background:{ALT};border:1px solid {DIV};border-radius:999px;padding:4px 18px 4px 14px">'
            f'<div style="width:14px;height:14px;background:{DOT[key]};border-radius:999px"></div>'
            f'<p style="font-size:24px;font-weight:700;color:{INK}">{word}</p></div>')


def P(text, size=24, color=INK, extra=""):
    return f'<p style="font-size:{size}px;line-height:1.3;color:{color};{extra}">{text}</p>'


def cap(text):
    return f'<p style="font-size:24px;font-weight:600;color:{MUTED}">{text}</p>'


def defline(text):
    return f'<p style="font-size:24px;line-height:1.3;color:{MUTED}">{text}</p>'


def parse(t):
    d = {"eyebrow": one(r'<p style="font-size:24px;font-weight:600;letter-spacing:2px;text-transform:uppercase;color:#B04A14">(.*?)</p>', t),
         "h2": one(r"<h2[^>]*>(.*?)</h2>", t)}
    q = re.search(r'<p style="font-family:\'Source Serif 4\', Georgia, serif;font-size:\d+px;font-style:italic;[^"]*border-left:6px solid (#[0-9A-F]+);[^"]*">(.*?)</p>', t, re.S)
    d["quote"], d["qcolor"] = (q.group(2), q.group(1)) if q else (None, None)
    d["take"] = one(r'<p style="font-size:\d+px;line-height:1.4;border-top:1px solid #DDD6CB;[^"]*">(.*?)</p>', t)
    items = []
    for line in t.split("\n"):
        if line.startswith('<p style="font-size:26px;color:#5E5850">'):
            items.append(("cap", one(r"<p[^>]*>(.*?)</p>", line)))
        elif line.startswith('<p style="width:') and "text-align:right" in line:
            items.append(["bar", one(r"<p[^>]*>(.*?)</p>", line), None, 0.0, None])
        elif line.startswith('<div style="width:740px'):
            inner = re.search(r'<div style="width:(\d+)px;height:\d+px;background:(#[0-9A-F]+);border-radius:\d+px"></div>', line)
            if inner:
                items[-1][3] = int(inner.group(1)) / 740
                items[-1][4] = inner.group(2)
        elif line.startswith('<p style="width:200px') or line.startswith('<p style="width:150px'):
            items[-1][2] = one(r"<p[^>]*>(.*?)</p>", line)
    d["items"] = items
    d["bars"] = [i for i in items if i[0] == "bar"]
    for b in d["bars"]:  # an empty bar takes the colour of a bar with the same label
        if b[4] is None:
            b[4] = next((x[4] for x in d["bars"] if x[1] == b[1] and x[4]), None)
    d["caps"] = [i[1] for i in items if i[0] == "cap"]
    return d


