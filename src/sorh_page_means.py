"""Means for two SoRH page charts (her doc comments "do mean", 27 Oct 15:58, on the reasoning-length and the
spiral charts). No new calls; recorded usage and the judges' labels only, no reasoning read.

  .venv/bin/python src/sorh_page_means.py   # writes notes/sorh_page_means.md

- Reasoning tokens: mean per cell and model over the same records as notes/sorh_models20_reasoning_length.md (one
  reply per prompt; a reply cut at a token limit keeps its recorded count, a lower bound). The medians are recomputed
  and asserted equal to that file's, so the records are the same.
- Score cycles: mean per cell and model over the replies counted in k/n of notes/sorh_hesitation_spiral_results_20.md
  (not cut during reasoning, a spiral label that passes the cited-sentence rule); the medians are recomputed and
  asserted equal to that file's.
Both without re-draws, like the verified files.
"""
import re
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import sorh_deepseek20 as D  # noqa: E402
import sorh_judge_pass as P  # noqa: E402
import sorh_page_graphs as G  # noqa: E402
import sorh_reasoning_length as L  # noqa: E402

OUT = ROOT / "notes" / "sorh_page_means.md"
MODELS = ["Qwen 3.8 2.4T", "DeepSeek V4 Pro", "GLM 5.2", "Qwen 3.8 27B"]


def token_records(with_redraws=False):
    models = {"Qwen 3.8 2.4T": {k: r for k, (_, r) in D.qwen_first().items()}}
    for lab, st, _ in D.MODELS:
        models[lab] = {(r["cell"], r["prompt_id"]): r for r in D.jl(ROOT / "logs/sorh_ablation" / st / "records.jsonl")}
    if with_redraws:  # as sorh_reasoning_length.py --with-redraws
        import sorh_redraws as RD
        for m in (RD.QWEN, RD.DS):
            models[m].update(RD.overlay(m))
    return models


def verified_medians(path, pat):
    """cell -> [the four models' medians] from a verified table, parsed with pat (one group per model cell)."""
    out, section = {}, None
    for line in open(path, encoding="utf-8"):
        if line.startswith("## "):
            section = line.strip()
        m = re.match(r"^\| (\w+) \| (.+) \|$", line.strip())
        if m and m.group(1) not in ("cell",):
            out.setdefault(section, {})[m.group(1)] = [pat(v) for v in m.group(2).split(" | ")]
    return out


def main(with_redraws=False):
    models = token_records(with_redraws)
    prompts = sorted({p for (_, p) in models["Qwen 3.8 2.4T"]})
    cells = list(dict.fromkeys(c for _, cs in D.HEADINGS for c in cs))
    ver = verified_medians(ROOT / ("notes/sorh_models20_reasoning_length_redraws.md" if with_redraws else "notes/sorh_models20_reasoning_length.md"),
                           lambda v: float(v.split(" [")[0].replace(",", "")))["## Reasoning tokens (as reported)"]
    lines = ["# Means for the reasoning-length and spiral charts (her 'do mean')" + (", with the re-draws" if with_redraws
                                                                                     else ""), "",
             "Generated by `src/sorh_page_means.py" + (" --with-redraws" if with_redraws else "") + "` (measures in its "
             "docstring). No new calls, no reasoning read. Same records as the verified files" +
             (" with the re-draws (src/sorh_redraws.py overlay) in place of the missing or cut replies; the medians are "
              "recomputed and match notes/sorh_models20_reasoning_length_redraws.md and "
              "notes/sorh_hesitation_spiral_results_20_redraws.md." if with_redraws else
              ", without re-draws; their medians are recomputed and match."), "",
             "## Mean reasoning tokens (as reported), her 20 prompts", "",
             "| cell | " + " | ".join(MODELS) + " |", "|---|" + "---|" * len(MODELS)]
    mean_tok = {}
    for c in cells:
        row = []
        for j, m in enumerate(MODELS):
            rs = [models[m][(c, p)] for p in prompts if (c, p) in models[m]]
            v = [L.rt(r) for r in rs if L.rt(r) is not None]
            assert round(statistics.median(v)) == round(ver[c][j]), (m, c, statistics.median(v), ver[c][j])
            cut = sum(r["finish"] == "length" for r in rs)
            mean_tok[(c, m)] = statistics.mean(v)
            row.append(f"{statistics.mean(v):,.0f}" + (f" ({cut} cut)" if cut else "") +
                       (f" ({20 - len(rs)} missing)" if len(rs) < 20 else ""))
        lines.append(f"| {c} | " + " | ".join(row) + " |")
    lines += ["", "Ratio of means, G / B: " + ", ".join(
        f"{m} {mean_tok[('G', m)] / mean_tok[('B', m)]:.1f}×" for m in MODELS) + ". A cut reply keeps its recorded "
              "count (a lower bound); a mean moves with the longest replies more than a median does.", ""]
    rows = G.replies(with_redraws)
    ver2 = verified_medians(ROOT / ("notes/sorh_hesitation_spiral_results_20_redraws.md" if with_redraws else "notes/sorh_hesitation_spiral_results_20.md"),
                            lambda v: float(re.search(r"cycles (\S+)", v).group(1)) if "cycles" in v else None)
    ver2 = next(v for k, v in ver2.items() if k and k.startswith("## Spirals"))
    lines += ["## Mean score cycles over the replies counted in k/n, her 20 prompts", "",
              "| cell | " + " | ".join(MODELS) + " |", "|---|" + "---|" * len(MODELS)]
    for c in P.CELLS:
        row = []
        for j, m in enumerate(MODELS):
            v = [r["cycles"] for r in rows if r["model"] == m and r["cell"] == c and r["counted"]
                 and r["cycles"] is not None]
            assert statistics.median(v) == ver2[c][j], (m, c, statistics.median(v), ver2[c][j])
            k = sum(r["spirals"] is True for r in rows if r["model"] == m and r["cell"] == c and r["counted"])
            row.append(f"{k}/{len(v)}, mean {statistics.mean(v):.1f}")
        lines.append(f"| {c} | " + " | ".join(row) + " |")
    counted = [r for r in rows if r["counted"] and r["cycles"] is not None]
    over = [r for r in counted if r["cycles"] > len(r["score_checks"])]
    lines += ["", "k/n as in the verified file; mean cycles over the same n replies.", "",
              f"**Caveat:** {len(over)} of {len(counted)} counted replies have more cycles than the score checks the "
              "judge listed (it lists at most 30, and each cycle needs a check), so those cycle counts can't be checked "
              "against its citations. They pull some means far above the median. The same means with each reply's "
              "cycles capped at its listed checks:", "",
              "| cell | " + " | ".join(MODELS) + " |", "|---|" + "---|" * len(MODELS)]
    for c in P.CELLS:
        lines.append(f"| {c} | " + " | ".join(
            f"{statistics.mean([min(r['cycles'], len(r['score_checks'])) for r in counted if r['model'] == m and r['cell'] == c]):.1f}"
            for m in MODELS) + " |")
    lines += ["", "Replies above their listed checks: " + "; ".join(
        f"{r['model']} {r['cell']}/{r['prompt']} {r['cycles']} cycles, {len(r['score_checks'])} checks"
        for r in sorted(over, key=lambda r: -r["cycles"])) + "."]
    out = OUT.with_name("sorh_page_means_redraws.md") if with_redraws else OUT
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main("--with-redraws" in sys.argv)
