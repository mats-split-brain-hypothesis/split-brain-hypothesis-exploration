"""G vs the class version (r_student), same model and prompt: where the padding label flips, and why (her "i need
some examples where i can explain why the models pad a bit less in the class examples", 27 Oct). No new calls; no
reasoning read. Labels = the page's main padding numbers (padding v2: the unchanged judge on the final output, the
no-output fix applied); old = that judge on the whole reply.

  .venv/bin/python src/sorh_class_padding_examples.py   # writes notes/sorh_class_padding_examples.md

Per model and prompt, both replies (the page tables' records): the new and old label, the judge's one-line reason,
the characters the cut removed (notes to the person around the final output), the final output's words, and the score
measure on the whole reply (the count judge's count, or its share in points). Then every pair where the label differs,
in both directions, with both final outputs in full.
"""
import statistics
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import sorh_analysis as SA  # noqa: E402
import sorh_deepseek20 as D  # noqa: E402
import sorh_judges as J  # noqa: E402
import sorh_padding_final as PF  # noqa: E402

OUT = ROOT / "notes" / "sorh_class_padding_examples.md"
MODELS = ["Qwen 3.8 2.4T", "DeepSeek V4 Pro", "GLM 5.2", "Qwen 3.8 27B"]
LAB = {"qwen/qwen3.8-2.4t-a95b": "Qwen 3.8 2.4T", "deepseek/deepseek-v4-pro": "DeepSeek V4 Pro",
       "z-ai/glm-5.2": "GLM 5.2", "qwen/qwen3.8-27b": "Qwen 3.8 27B"}
CELLS = ("G", "r_student")
NOTE = 40  # characters cut around the final output that count as a note to the person


def rows():
    base = ROOT / "logs/sorh_ablation"
    lab = {x["key"]: x for x in D.jl(base / PF.OUTDIR / PF.V2_OUT)}
    for x in D.jl(base / PF.OUTDIR / PF.FIX_OUT):
        lab[x["key"]] = dict(lab[x["key"]], padding_final_nometric=x["padding_final_nometric"], why=x.get("why"),
                             fixed_whole=True)
    btext = {r["prompt_id"]: r["text"] for r in D.jl(D.OUT) if r["cell"] == "B"}
    req = {(r["cell"], r["prompt_id"]): r["text"] for r in D.jl(D.OUT)}
    out = {}
    for st, i, r in PF.table_set(base):
        if r["cell"] not in CELLS:
            continue
        reply = r.get("reply") or ""
        if r.get("finish") == "length" and not reply.strip():
            continue  # cut during reasoning: missing (a7d6e9f)
        x = lab[PF.key(st, i, r)]
        if x.get("fixed_whole") or x["has_output"] is False or x.get("cut_failed"):
            final = reply  # what the judge saw: the whole reply (run_v2 keeps it when the anchors fail twice)
        else:
            raw = (x.get("cut_raws") or [None])[-1]
            final = (PF.parse_cut(raw, reply)[1] if raw else None) or reply
        assert len(reply) - len(final) == (x.get("chars_removed") or 0) or x.get("fixed_whole"), PF.key(st, i, r)
        meas = SA.measures(r, btext[r["prompt_id"]])
        out[(LAB[r["model"]], r["prompt_id"], r["cell"])] = {
            "new": x["padding_final_nometric"], "old": x["old_padded"], "why": x.get("why"),
            "removed": x.get("chars_removed") or 0, "final": final or "", "words": J.words(final or ""),
            "value": meas["value"], "share": r["row"] in J.SHARE_ROWS, "request": req[(r["cell"], r["prompt_id"])]}
    return out


def fmt_v(x):
    return "—" if x["value"] is None else (f"{x['value']:.1f} points" if x["share"] else f"{x['value']} counted")


def main():
    data = rows()
    prompts = sorted({p for _, p, _ in data})
    flips = defaultdict(list)
    for m in MODELS:
        for p in prompts:
            g, s = data.get((m, p, "G")), data.get((m, p, "r_student"))
            if g and s and g["new"] is not None and s["new"] is not None and g["new"] != s["new"]:
                flips[(m, "G padded, class not" if g["new"] else "class padded, G not")].append(p)
    lines = ["# Why the class version pads a bit less: G vs class, same model and prompt", "",
             "Generated by `src/sorh_class_padding_examples.py` (measures in its docstring). Labels are the page's "
             "main padding numbers (the judge on the final output, notes to the person cut away); 'old' is the same "
             "judge on the whole reply. No reasoning read.", "",
             "## Flips per model (same prompt, label differs)", "",
             "| model | G padded | class padded | G padded, class not | class padded, G not |", "|---|---|---|---|---|"]
    for m in MODELS:
        gp = sum(1 for p in prompts if (data.get((m, p, "G")) or {}).get("new"))
        sp = sum(1 for p in prompts if (data.get((m, p, "r_student")) or {}).get("new"))
        lines.append(f"| {m} | {gp}/20 | {sp}/20 | {len(flips[(m, 'G padded, class not')])} "
                     f"({', '.join(flips[(m, 'G padded, class not')]) or '—'}) | "
                     f"{len(flips[(m, 'class padded, G not')])} ({', '.join(flips[(m, 'class padded, G not')]) or '—'}) |")
    lines += ["", "## All 20 pairs per model: notes to the person, and how hard the reply games the score", "",
              f"A note = more than {NOTE} characters cut around the final output (Qwen 3.8 27B's 2-character cuts are "
              "leftover whitespace). Score measure on the whole reply, class vs G, where both have one; ratio = "
              "(class + 1) / (G + 1).", "",
              "| model | replies with a note, G | with a note, class | median characters cut, class | score measure "
              "class < G | class > G | equal | median ratio | median final-output words, G → class |",
              "|---|---|---|---|---|---|---|---|---|"]
    for m in MODELS:
        pairs = [(data[(m, p, "G")], data[(m, p, "r_student")]) for p in prompts
                 if (m, p, "G") in data and (m, p, "r_student") in data]
        vals = [(a["value"], b["value"]) for a, b in pairs if a["value"] is not None and b["value"] is not None]
        lo, hi = sum(b < a for a, b in vals), sum(b > a for a, b in vals)
        lines.append(f"| {m} | {sum(a['removed'] > NOTE for a, _ in pairs)}/{len(pairs)} | "
                     f"{sum(b['removed'] > NOTE for _, b in pairs)}/{len(pairs)} | "
                     f"{statistics.median([b['removed'] for _, b in pairs]):.0f} | {lo} | {hi} | {len(vals) - lo - hi} | "
                     f"{statistics.median([(b + 1) / (a + 1) for a, b in vals]):.2f} | "
                     f"{statistics.median([a['words'] for a, _ in pairs]):.0f} → "
                     f"{statistics.median([b['words'] for _, b in pairs]):.0f} |")
    lines += ["", "## Every flip, both replies", ""]
    for direction in ("G padded, class not", "class padded, G not"):
        lines += [f"### {direction}", ""]
        for m in MODELS:
            for p in flips[(m, direction)]:
                lines += [f"#### {m}, {p}", ""]
                for c in CELLS:
                    x = data[(m, p, c)]
                    lines += [f"**{'G' if c == 'G' else 'Class'}**: padded {x['new']} (old judge on the whole reply: "
                              f"{x['old']}); score measure {fmt_v(x)}; final output {x['words']} words; "
                              f"{x['removed']} characters of notes cut around it.", "",
                              f"Judge's reason: {x['why']}", "", "> " + x["final"].strip().replace("\n", "\n> "), ""]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    for k, v in flips.items():
        print(k, len(v), v)


if __name__ == "__main__":
    main()
