"""Quotes for her four-model SoRH page (her "we need quotes in [SoRH] for each one", 2026-10-27, via the orchestrator).

The rule, fixed before any of these replies was read:
- one prompt for every finding: sorh_160 (the sleep social-media post, from her 10);
- the cells per finding: #1 B, G, r_student; #2 c2_vague, c3a_exam, c3a_conv; #3 c4_auto, c5_eval, c5_real;
  #5 c6_quality_first, c7_dont_care, c6_score_first, r_student__c6_quality_first. G, from #1, is #5's reference;
- each model's first reply on that cell: sample 0, or for Qwen 3.8 2.4T its first sample, as in the results;
- the excerpt is the reply's opening: whitespace collapsed to single spaces, the first 300 characters, cut back to the
  last space and ended with "…" if longer;
- beside each excerpt: that reply's padded flag, and the cell's padded k/n for that model on all 20 prompts;
- reasoning only on Qwen 2.4T, and only sentences the v4-sol reasoning judge already cited. That is one sentence per
  finding, from #1 G, #2 c3a_exam, #3 c5_real and #5 c6_quality_first: the first sentence cited for plans_for_score if
  it is labelled true, else for plans_for_reader, else none. No other reasoning is read.

  .venv/bin/python src/sorh_quotes.py     # writes notes/sorh_models20_quotes.md
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import sorh_deepseek20 as D  # noqa: E402
import sorh_judges as J  # noqa: E402

PROMPT = "sorh_160"
FINDINGS = [("#1", D.HEADINGS[0][0], ["B", "G", "r_student"], "G"),
            ("#2", D.HEADINGS[1][0], ["c2_vague", "c3a_exam", "c3a_conv"], "c3a_exam"),
            ("#3", D.HEADINGS[2][0], ["c4_auto", "c5_eval", "c5_real"], "c5_real"),
            ("#5", D.HEADINGS[3][0], ["c6_quality_first", "c7_dont_care", "c6_score_first",
                                      "r_student__c6_quality_first"], "c6_quality_first")]
OUT = ROOT / "notes" / "sorh_models20_quotes.md"


def excerpt(text, n=300):
    t = " ".join((text or "").split())
    if len(t) <= n:
        return t
    cut = t[:n]
    return (cut[:cut.rfind(" ")] if " " in cut else cut) + " …"


def main():
    qwen = {k: (st, r) for k, (st, r) in D.qwen_first().items()}
    models = [("Qwen 3.8 2.4T", None)] + [(lab, st) for lab, st, _ in D.MODELS]
    recs = {}
    for lab, st in models[1:]:
        recs[lab] = {(r["cell"], r["prompt_id"]): (st, r) for r in D.jl(ROOT / "logs/sorh_ablation" / st / "records.jsonl")}
    recs["Qwen 3.8 2.4T"] = qwen

    def kn(lab, cell):
        v = [D.padded_of(recs[lab][(cell, p)][1]) for p in sorted({p for (_, p) in qwen})
             if (cell, p) in recs[lab]]
        ok = [x for x in v if x is not None]
        return f"{sum(ok)}/{len(ok)}"

    lines = ["# Quotes for her SoRH single-turn conclusions, four models (agent 1, 2026-10-27)", "",
             "Generated by `src/sorh_quotes.py`. The selection rule, fixed before any of these replies was read, is "
             "in the script's docstring: one prompt for every finding (sorh_160, the sleep social-media post); each "
             "model's first reply on the listed cells; the reply's opening 300 characters (whitespace collapsed, cut "
             "at a space, '…' if longer). Each excerpt carries that reply's padded flag (quality judge) and the "
             "cell's padded k/n on all 20 prompts for that model. Reasoning: Qwen 3.8 2.4T only, one sentence per "
             "finding, the one the v4-sol reasoning judge cited first. Every quote gives its source file and record "
             "key.", ""]
    for num, head, cells, rcell in FINDINGS:
        lines += [f"## {head}", ""]
        for cell in cells:
            lines += [f"### {cell}", ""]
            for lab, st in models:
                st_r, r = recs[lab][(cell, PROMPT)]
                src = f"logs/sorh_ablation/{st_r}/records.jsonl"
                pad = D.padded_of(r)
                lines += [f"- **{lab}**: padded {'yes' if pad else 'no' if pad is False else 'missing'} (cell {kn(lab, cell)})."
                          f" Reply: \"{excerpt(r.get('reply'))}\"",
                          f"  - source `{src}`, record {r['cell']}/{r['prompt_id']}/{r['sample']}, reply "
                          f"({r['finish']}, {len((r.get('reply') or '').split())} words)"]
            lines.append("")
        st_r, r = qwen[(rcell, PROMPT)]
        z = J.parse_reasoning((r.get("judge") or {}).get("reasoning"), r.get("reasoning") or "")
        raw = J._load((r.get("judge") or {}).get("reasoning")) or {}
        q, field = None, None
        for f in ("plans_for_score", "plans_for_reader"):
            if z.get(f) and (raw.get(f) or {}).get("sentences"):
                q, field = J.cited_text(raw[f]["sentences"][:1], r.get("reasoning") or ""), f
                break
        if q:
            lines += [f"Judge-cited reasoning (Qwen 3.8 2.4T, {rcell}): the judge labelled {field} true and cited: "
                      f"\"{' '.join(' '.join(q).split())}\"",
                      f"  - source `logs/sorh_ablation/{st_r}/records.jsonl`, record {r['cell']}/{r['prompt_id']}/"
                      f"{r['sample']}, reasoning sentence cited by the judge ({r.get('judge_version')}, "
                      f"{(r.get('judge_model') or {}).get('reasoning')})", ""]
        else:
            lines += [f"Judge-cited reasoning (Qwen 3.8 2.4T, {rcell}): neither plans_for_score nor plans_for_reader "
                      "is labelled true with a citation; no reasoning quoted.", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
