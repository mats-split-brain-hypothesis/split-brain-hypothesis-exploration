"""Run ledger for the 6x3 top-up and Test A (her (b) on the watchdog undercount, 27 Oct: keep the planned caps; record
each run's final bill against its last watchdog reading and its cap, and flag any final above its cap).

    .venv/bin/python src/run_ledger_ib11.py notes/ib_run_ledger_ib11.md

Per finished run dir (one runner process): the PID and cap from its watchdog.log start line, the last live "own spend"
reading, the final spend from the finished .eval (src/run_spend.own_spend: token estimate, and x1.3 = the guard scale
the cap is set on), OpenRouter's billed usage.cost summed over model calls, and a flag when the final on the guard
scale is above the cap. Metadata only. Runs still in progress are listed as running.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))


# Her decisions on runs that may end above their cap (relayed by the orchestrator, 27 Oct), recorded with the run.
DECISIONS = [
    ("all runs from 20:16Z", "On the watchdog undercount, options (a) half caps, (b) keep the planned caps and accept "
                             "the overshoot, (c) hold, (d) fix the measurement: her answer (b). Qwen 2.4T rejection "
                             "s1 (cap $6.77, worst case ~$13) and GLM Test A s1 launched under it."),
    ("logs/ib_chat_grader/glm_s1", "Question: \"Keep it running and accept up to ~$3 over the cap, or stop it at the "
                                   "cap?\" Her answer: \"Keep running (Recommended)\", i.e. she accepts a final up to "
                                   "~$11 against the $8 cap."),
]


# Runs flagged above their cap, with what the flag means (reported to the orchestrator and agent 2 when found).
FLAGS = [
    ("logs/ib_chat_rejection/ds_topup_s2_resume", "launched 20:12Z, before her (b), as one of two small runs agent 2 "
     "registered; final $0.65 on the guard scale vs cap $0.62 (+$0.03; billed $0.50); DeepSeek's rejection part over "
     "its two runs: $3.38 + $0.65 = $4.03 vs its $4.00 part cap."),
]


def dirs():
    import ib_grader_cells as G
    import ib_topup as T
    out = []
    for m in T.MODELS:
        for part in ("homework", "rejection", "chat"):
            out += [T.topup_dir(m, part, s) for s in T.STAGES]
        out += G.grader_dirs(m)
    return [d for d in out if (ROOT / d / "watchdog.log").exists()]


def billed(d):
    """Sum of OpenRouter's usage.cost over the model calls in the finished .eval files of d."""
    from inspect_ai.log import read_eval_log
    total = 0.0
    for f in sorted((ROOT / d).glob("*.eval")):
        if read_eval_log(str(f), header_only=True).status == "started":
            continue
        for s in read_eval_log(str(f)).samples or []:
            for e in s.events:
                if e.event != "model" or not e.call:
                    continue
                r = e.call.response or {}
                total += float(((r.get("usage") or {}).get("cost")) or 0) if isinstance(r, dict) else 0.0
    return total


def row(d):
    from inspect_ai.log import read_eval_log
    from run_spend import own_spend
    lines = (ROOT / d / "watchdog.log").read_text().splitlines()
    start = next(l for l in lines if " start " in l)
    pid = re.search(r"pid (\d+)", start).group(1)
    cap = float(re.search(r"cap \$([0-9.]+)", start).group(1))
    live = [float(re.search(r"own spend ~\$([0-9.]+)", l).group(1)) for l in lines if "own spend ~$" in l]
    files = sorted((ROOT / d).glob("*.eval"))
    done = bool(files) and all(read_eval_log(str(f), header_only=True).status != "started" for f in files)
    if not done:
        return dict(dir=d, pid=pid, cap=cap, status="running")
    tok, guard, n = own_spend(str(ROOT / d))
    b = billed(d)
    return dict(dir=d, pid=pid, cap=cap, status="done", samples=n, last_live=live[-1] if live else None,
                max_live=max(live) if live else None, final_token=tok, final_guard=guard, billed=b,
                over_cap=guard > cap)


def main(dest):
    rows = [row(d) for d in dirs()]
    out = ["# IB top-up and Test A: run ledger", "",
           "Her (b), 27 Oct: the planned caps stay; the watchdog's live reading undercounts chat runs (calls that end "
           "between polls are missed), so each run's final is recorded here against its last live reading and its "
           "cap. Cap and guard-scale final = token estimate x 1.3; billed = OpenRouter usage.cost from the logs. "
           "Generated by src/run_ledger_ib11.py.", "",
           "| Run dir | PID | Samples | Cap | Last live | Final, guard scale | Final ratio to last live | Token est. "
           "| Billed | Over cap |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if r["status"] != "done":
            out.append(f"| {r['dir']} | {r['pid']} | running | ${r['cap']:.2f} | | | | | | |")
            continue
        ratio = f"{r['final_guard'] / r['last_live']:.2f}" if r["last_live"] else "n/a (live $0)"
        out.append(f"| {r['dir']} | {r['pid']} | {r['samples']} | ${r['cap']:.2f} | ${r['last_live']:.2f} "
                   f"| ${r['final_guard']:.2f} | {ratio} | ${r['final_token']:.2f} | ${r['billed']:.2f} "
                   f"| {'**YES**' if r['over_cap'] else 'no'} |")
    done = [r for r in rows if r["status"] == "done"]
    out += ["", f"Finished runs: {len(done)}; over cap: {sum(r['over_cap'] for r in done)}; total billed "
                f"${sum(r['billed'] for r in done):.2f}, token estimate ${sum(r['final_token'] for r in done):.2f}, "
                f"guard scale ${sum(r['final_guard'] for r in done):.2f}.",
            "", "## Her decisions on caps", ""]
    out += [f"- **{what}:** {text}" for what, text in DECISIONS]
    out += ["", "## Finals above their cap", ""]
    out += [f"- **{what}:** {text}" for what, text in FLAGS]
    (ROOT / dest).write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "notes/ib_run_ledger_ib11.md")
