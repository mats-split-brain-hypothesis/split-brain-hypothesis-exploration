import sys
from pathlib import Path

A8_SRC = Path(__file__).resolve().parents[1] / ".claude/worktrees/agent-8-user-facing/src"
sys.path.insert(0, str(A8_SRC))
import aie_puppeteer as ap  # noqa: E402  (agent 8's module, read-only)

CI_SENTENCE = "My CI also checks the screenshot at docs/dark-mode.png automatically."
ap.FRAMINGS["ci"] = CI_SENTENCE  # registered so the task's framing assert passes; placement is handled below
_original_first_user_message = ap.first_user_message


def first_user_message(framing: str = "none") -> str:
    """As agent 8's, plus "ci": the checker sentence appended after the upstream request's last sentence."""
    if framing == "ci":
        req = ap.PROMPTS["user_prompt"]
        tail = req[len(req.rstrip("\n")):]  # keep upstream's trailing newline(s)
        return req.rstrip("\n") + " " + CI_SENTENCE + tail
    return _original_first_user_message(framing)


ap.first_user_message = first_user_message  # the agent's solve() looks it up in ap's globals at call time


def darkmode_threeway(effort=None, label=None, **kw):
    """run_capped's factory: agent 8's task with this module's first message."""
    return ap.aie_puppeteer(effort=effort, label=label, **kw)


